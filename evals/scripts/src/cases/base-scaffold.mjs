// The one base-commit scaffold builder: an isolated one-commit copy of the tree at a review's base, taken from the
// benchmark project's history (`<project>/.git`) with `git archive`, so no history after the base is reachable and
// the checkout is not touched. Reuse cases and task cases call it.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PROJECT_CODE_DIRECTORY, projectCodeDir } from '../shared/bench-paths.mjs';

const FIXED_DATE = '2026-01-01T00:00:00Z';

const quote = (text) => `'${String(text).replace(/'/g, `'\\''`)}'`;

const relativeFrom = (caseDir, target) => path.relative(caseDir, target).split(path.sep).join('/');
/** The project directory relative to the case directory, so the scaffold works where the case was generated, under any benchmark root. */
export const sideRelFrom = (caseDir, benchmarks, project) => relativeFrom(caseDir, path.join(benchmarks, project));
/** The project's code checkout relative to the case directory, for snapshot scaffolds. */
export const codeRelFrom = (caseDir, benchmarks, project) => relativeFrom(caseDir, projectCodeDir(benchmarks, project));

/** The base commit and code root a review version was taken at. */
export function baseOf(versionDir) {
  const file = path.join(versionDir, 'version.json');
  if (!existsSync(file)) throw new Error(`version.json is missing in ${versionDir}`);
  const { base, root } = JSON.parse(readFileSync(file, 'utf8'));
  if (typeof base !== 'string' || !/^[0-9a-f]{40}$/.test(base)) throw new Error(`version.json field "base" is not a 40-character commit id in ${versionDir}`);
  if (typeof root !== 'string' || root === '') throw new Error(`version.json field "root" is empty in ${versionDir}`);
  return { base, root };
}

/**
 * `sideRel` is the project directory relative to the script's own location. `withhold` paths are relative to the repo.
 * `wholeTree` extracts the whole base tree (manifests, lock file, runner config) instead of `root` alone; `config`
 * names a config file beside the script that replaces the side's. `applyPatch` names a patch beside the script.
 */
export function baseScaffoldScript({ sideRel, base, root, withhold = [], setup = null, wholeTree = false, config = null, applyPatch = null }) {
  for (const entry of withhold)
    if (path.posix.isAbsolute(entry) || entry.split('/').includes('..')) throw new Error(`withhold path must stay inside the repo: ${entry}`);
  const lines = [
    '#!/bin/sh',
    '# Generated by base-scaffold.mjs; regenerate rather than edit.',
    'set -e',
    `SIDE="$(cd "$(dirname "$0")"/${quote(sideRel)} && pwd)"`,
    'CACHE="$SIDE/.git"',
    'if [ ! -d "$CACHE" ]; then',
    '  echo "scaffold: no $SIDE/.git: the benchmark project clone is missing" >&2',
    '  exit 2',
    'fi',
    `if ! git -C "$CACHE" cat-file -e ${quote(`${base}^{commit}`)} 2>/dev/null; then`,
    '  echo "scaffold: base commit not in cache" >&2',
    '  exit 2',
    'fi',
    'mkdir -p "$PWD/repo/.ambicode"',
    wholeTree ? `git -C "$CACHE" archive ${quote(base)} | tar -x -C "$PWD/repo"` : `git -C "$CACHE" archive ${quote(base)} -- ${quote(root)} | tar -x -C "$PWD/repo"`,
    config ? `cp "$(dirname "$0")"/${quote(config)} "$PWD/repo/.ambicode/config.yaml"` : `cp "$SIDE/${PROJECT_CODE_DIRECTORY}/.ambicode/config.yaml" "$PWD/repo/.ambicode/config.yaml"`,
    ...withhold.map((entry) => `rm -rf -- ${quote(`repo/${entry}`)}`),
  ];
  if (setup)
    lines.push(`(cd "$PWD/repo" && ${setup.argv.map(quote).join(' ')}) || {`, '  code=$?', '  echo "scaffold: dependency setup failed (exit $code)" >&2', '  exit 3', '}');
  lines.push(
    'git -C "$PWD/repo" init -q',
    'git -C "$PWD/repo" add -A',
    `GIT_AUTHOR_NAME="AMBICODE Benchmark" GIT_AUTHOR_EMAIL=benchmark@example.invalid GIT_AUTHOR_DATE=${FIXED_DATE} \\`,
    `  GIT_COMMITTER_NAME="AMBICODE Benchmark" GIT_COMMITTER_EMAIL=benchmark@example.invalid GIT_COMMITTER_DATE=${FIXED_DATE} \\`,
    '  git -C "$PWD/repo" -c commit.gpgsign=false commit -q -m "benchmark base"',
  );
  // A review case's change, applied after the commit so it stays uncommitted: the reviewer sees it as the diff.
  if (applyPatch) lines.push(`git -C "$PWD/repo" apply --binary "$(cd "$(dirname "$0")" && pwd)"/${quote(applyPatch)}`);
  lines.push('');
  return lines.join('\n');
}

export function writeBaseScaffold(caseDir, options) {
  writeFileSync(path.join(caseDir, 'scaffold.sh'), baseScaffoldScript(options), { mode: 0o755 });
}
