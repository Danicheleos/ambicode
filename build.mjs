// Bundles the helper sources into one distributable entry point under scripts/.
// Bundling (rather than shipping tsc output plus node_modules) keeps the
// installed plugin runnable without an install step inside a product repository.
import { build } from 'esbuild';
import { chmod, mkdir, rm, writeFile } from 'node:fs/promises';

await rm(new URL('./scripts/ambicode.mjs', import.meta.url), { force: true });

await build({
  entryPoints: ['src/cli/main.ts'],
  outfile: 'scripts/ambicode.mjs',
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  sourcemap: false,
  legalComments: 'none',
  // `yaml` is CommonJS and calls require('process') at load time; esbuild's ESM
  // require shim refuses builtins, so a real require is supplied for it to find.
  banner: {
    js: [
      '#!/usr/bin/env node',
      "import { createRequire as __ambicodeCreateRequire } from 'node:module';",
      'const require = __ambicodeCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'info',
});

// Claude Code puts a plugin's `bin/` on the Bash tool's PATH, so skills invoke
// `ambicode` by name. A shell wrapper, not a renamed bundle: `node` reads module
// type from the nearest package.json and the wrapper does not depend on that.
const binDirectory = new URL('./bin/', import.meta.url);
await mkdir(binDirectory, { recursive: true });
const launcher = new URL('./ambicode', binDirectory);
await writeFile(
  launcher,
  ['#!/bin/sh', '# Generated by build.mjs; edit src/cli/main.ts instead.', 'exec node "$(dirname "$0")/../scripts/ambicode.mjs" "$@"', ''].join('\n'),
);
await chmod(launcher, 0o755);
